let currentLocale = 'es';

function detectLocale() {
  const saved = localStorage.getItem('quba_locale');
  if (saved && I18N[saved]) return saved;
  const browserLang = (navigator.language || 'es').split('-')[0];
  return I18N[browserLang] ? browserLang : 'es';
}

function setLocale(loc) {
  if (!I18N[loc]) return;
  currentLocale = loc;
  localStorage.setItem('quba_locale', loc);
  document.documentElement.lang = loc;
  document.documentElement.dir = loc === 'ar' ? 'rtl' : 'ltr';
  applyTranslations();
}

function t(key) {
  return I18N[currentLocale]?.[key] || I18N.es[key] || key;
}

// v21: resolve a possibly-trilingual value ({es, ar, en} object or plain string)
// to the current UI language, with graceful fallbacks.
function L(val) {
  if (val == null) return '';
  if (typeof val !== 'object') return val;
  return val[currentLocale] || val.es || val.en || Object.values(val)[0] || '';
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  // v21: translate page <title> and meta description on locale switch
  document.title = t('metaTitle') || 'Quba';
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', t('metaDesc') || '');
}

currentLocale = detectLocale();
document.documentElement.lang = currentLocale;
document.documentElement.dir = currentLocale === 'ar' ? 'rtl' : 'ltr';
