function getCalendarInfo(date) {
  // ⚠️ FIX: una cadena 'YYYY-MM-DD' se interpreta como medianoche UTC y, en
  // zonas horarias negativas (La Habana UTC-4), retrocede al DÍA ANTERIOR —
  // por eso el fadal del viernes aparecía al pulsar el sábado. Se parsea
  // manualmente como fecha LOCAL (mediodía) para que coincida siempre.
  if (!(date instanceof Date)) {
    const s = String(date);
    const m = s.match(/^(\d{4})-(\d{2})-(\d{2})/);
    if (m) {
      date = new Date(parseInt(m[1], 10), parseInt(m[2], 10) - 1, parseInt(m[3], 10), 12, 0, 0, 0);
    } else {
      date = new Date(s);
    }
  }
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  const key = `${y}-${m}-${d}`;
  const infoKey = CALENDAR_2026_MAP[key];
  if (infoKey && CALENDAR_INFO[infoKey]) {
    return { ...CALENDAR_INFO[infoKey], key: infoKey, date: key };
  }
  // Fallback: friday detection (usa fecha local ya corregida)
  if (date.getDay() === 5 && CALENDAR_INFO.friday) {
    return { ...CALENDAR_INFO.friday, key: 'friday', date: key };
  }
  return CALENDAR_INFO.regular ? { ...CALENDAR_INFO.regular, key: 'regular', date: key } : null;
}

/**
 * Get info by key (e.g. 'ramadan', 'friday')
 */
function getCalendarInfoByKey(key) {
  return CALENDAR_INFO[key] || null;
}

if (typeof window !== 'undefined') {
  window.CALENDAR_2026_MAP = CALENDAR_2026_MAP;
  window.CALENDAR_INFO = CALENDAR_INFO;
  window.getCalendarInfo = getCalendarInfo;
  window.getCalendarInfoByKey = getCalendarInfoByKey;
}
