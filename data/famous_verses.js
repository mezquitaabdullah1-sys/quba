function getFamousVerseOfTheDay() {
  const today = new Date();
  const start = new Date(today.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((today - start) / 86400000);
  return FAMOUS_VERSES[dayOfYear % FAMOUS_VERSES.length];
}

